// Package render turns custos.json (plus derived state) into the files the
// system reads: an nft fragment, systemd-networkd drop-ins, WireGuard
// netdevs and hostapd configuration. Rendering is pure: same input, same
// bytes. That is what makes custos-apply idempotent.
package render

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
	"time"

	"github.com/martincvitic19/custos-marginis/custos/internal/config"
	"github.com/martincvitic19/custos-marginis/custos/internal/curfew"
	"github.com/martincvitic19/custos-marginis/custos/internal/state"
)

// Input is everything a render needs.
type Input struct {
	Cfg   *config.Config
	State *state.State
	Now   time.Time
	// MullvadUp: a Mullvad configuration exists (wg-mullvad is rendered).
	MullvadUp bool
	// WGIf is the WireGuard server interface (wg0).
	WGIf string
}

func q(s string) string { return `"` + s + `"` } // inputs are validated: no quotes

func elemDev(d config.Device, c *config.Config) string {
	return d.MAC + " . " + q(c.VLANIf(d.VLAN))
}

// set renders "flush set" + "add element" for one set.
func set(b *strings.Builder, name string, elems []string) {
	fmt.Fprintf(b, "flush set inet custos %s\n", name)
	if len(elems) == 0 {
		return
	}
	sort.Strings(elems)
	fmt.Fprintf(b, "add element inet custos %s { %s }\n", name, strings.Join(elems, ", "))
}

// CurfewSnapshot is who is blocked right now; custos-apply compares it with
// the previous run to know whose connections to flush.
type CurfewSnapshot struct {
	Unknown bool     `json:"unknown_children"`
	Devices []string `json:"devices"` // device names
	Peers   []string `json:"peers"`
}

// Curfew evaluates every schedule at in.Now.
func Curfew(in Input) CurfewSnapshot {
	s := CurfewSnapshot{Unknown: curfew.UnknownBlocked(in.Cfg, in.Now), Devices: []string{}, Peers: []string{}}
	for _, d := range in.Cfg.Devices {
		if curfew.DeviceBlocked(in.Cfg, d, in.Now) {
			s.Devices = append(s.Devices, d.Name)
		}
	}
	for _, p := range in.Cfg.VPN.Peers {
		if curfew.PeerBlocked(in.Cfg, p, in.Now) {
			s.Peers = append(s.Peers, p.Name)
		}
	}
	return s
}

func strict(c *config.Config, d config.Device) bool {
	if d.StrictEgress != nil {
		return *d.StrictEgress
	}
	return c.RoleOf(d.Role).StrictEgress
}

// NFT renders /run/custos/firewall/50-custos-policy.nft. It works both as
// a stand-alone transaction (nft -f, custos-apply) and as part of the base
// ruleset load (custos-firewall includes /run/custos/firewall/*.nft after
// creating the table, so a firewall reload keeps the policy).
//
// The base ruleset declares the chains policy_pre, roles, policy_input
// and policy_snat empty and jumps to them; this file fills them.
func NFT(in Input) string {
	c := in.Cfg
	lan := make([]string, 0)
	for _, i := range c.LANIfs() {
		lan = append(lan, q(i))
	}
	lanSet := "{ " + strings.Join(lan, ", ") + " }"
	wg := q(in.WGIf)
	snap := Curfew(in)
	blocked := map[string]bool{}
	for _, n := range snap.Devices {
		blocked[n] = true
	}
	peerBlocked := map[string]bool{}
	for _, n := range snap.Peers {
		peerBlocked[n] = true
	}

	var known, trusted, unfiltered, curfewSet, strictSet []string
	for _, d := range c.Devices {
		e := elemDev(d, c)
		known = append(known, e)
		switch d.Role {
		case config.RoleTrusted:
			trusted = append(trusted, e)
		case config.RoleUnfiltered:
			unfiltered = append(unfiltered, e)
		}
		if blocked[d.Name] {
			curfewSet = append(curfewSet, e)
		}
		if strict(c, d) {
			strictSet = append(strictSet, e)
		}
	}
	var peerCurfew, peerStrict []string
	for _, p := range c.VPN.Peers {
		if peerBlocked[p.Name] {
			peerCurfew = append(peerCurfew, p.Address)
		}
		if c.RoleOf(p.Role).StrictEgress {
			peerStrict = append(peerStrict, p.Address)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by custos-apply from /data/custos/custos.json. Do not edit:
# the next custos-apply run overwrites it (no timestamp here on purpose:
# the same input must give the same bytes).
#
# Devices are identified by MAC . VLAN interface: the same MAC on another
# VLAN is an unknown device, and unknown devices are children.

table inet custos {
	set dev_known { type ether_addr . ifname; comment "every device in custos.json"; }
	set dev_trusted { type ether_addr . ifname; comment "role trusted (admin VLAN only)"; }
	set dev_unfiltered { type ether_addr . ifname; comment "role unfiltered"; }
	set curfew_block { type ether_addr . ifname; comment "known devices in curfew now"; }
	set egress_strict { type ether_addr . ifname; comment "known devices limited to web + NTP"; }
	set peer_curfew_block { type ipv4_addr; comment "VPN peers in curfew now"; }
	set peer_egress_strict { type ipv4_addr; comment "VPN peers limited to web + NTP"; }

	# Traffic accounting for the bypass and upload alerts (custos-watch).
	# Not flushed on apply, so counters keep running.
	set acct_tx { type ether_addr . ifname; flags dynamic; size 4096; counter; comment "bytes sent to the internet per device"; }
	set acct_dns { type ether_addr . ifname; flags dynamic; size 4096; counter; comment "DNS packets to Custos per device"; }

	# Chains are declared empty here and filled below after a flush: rules
	# inside a table block would be appended again on every apply.
	chain acct_forward {
		type filter hook forward priority filter - 10; policy accept;
	}
	chain acct_input {
		type filter hook input priority filter - 10; policy accept;
	}
	chain child_egress {
	}
}

flush chain inet custos acct_forward
add rule inet custos acct_forward iifname %[2]s oifname %[3]s update @acct_tx { ether saddr . iifname }
flush chain inet custos acct_input
add rule inet custos acct_input iifname %[2]s meta l4proto { tcp, udp } th dport 53 update @acct_dns { ether saddr . iifname }
flush chain inet custos child_egress
add rule inet custos child_egress tcp dport { 80, 443 } return
add rule inet custos child_egress udp dport { 123, 443 } return
add rule inet custos child_egress counter drop comment "child egress: not web/NTP"

`, "", lanSet, q(c.Network.WAN))

	set(&b, "dev_known", known)
	set(&b, "dev_trusted", trusted)
	set(&b, "dev_unfiltered", unfiltered)
	set(&b, "curfew_block", curfewSet)
	set(&b, "egress_strict", strictSet)
	set(&b, "peer_curfew_block", peerCurfew)
	set(&b, "peer_egress_strict", peerStrict)

	// policy_pre runs in forward BEFORE "ct state established accept", so a
	// curfew also stops connections that are already open.
	b.WriteString("\nflush chain inet custos policy_pre\n")
	fmt.Fprintf(&b, "add rule inet custos policy_pre iifname %s ether saddr . iifname @curfew_block counter drop comment %s\n",
		lanSet, q("curfew: device"))
	if snap.Unknown {
		fmt.Fprintf(&b, "add rule inet custos policy_pre iifname %s ether saddr . iifname != @dev_known counter drop comment %s\n",
			lanSet, q("curfew: unknown device (child role)"))
	}
	fmt.Fprintf(&b, "add rule inet custos policy_pre iifname %s ip saddr @peer_curfew_block counter drop comment %s\n",
		wg, q("curfew: VPN peer"))

	// roles runs for new connections, after dns_guard.
	b.WriteString("\nflush chain inet custos roles\n")
	fmt.Fprintf(&b, "add rule inet custos roles iifname %s ether saddr . iifname @egress_strict jump child_egress\n", lanSet)
	if c.RoleOf(config.RoleChild).StrictEgress {
		fmt.Fprintf(&b, "add rule inet custos roles iifname %s ether saddr . iifname != @dev_known jump child_egress\n", lanSet)
	}
	if c.VPN.Enabled {
		fmt.Fprintf(&b, "add rule inet custos roles iifname %s ip saddr @peer_egress_strict jump child_egress\n", wg)
		switch {
		case c.VPN.Exit == "wan":
			fmt.Fprintf(&b, "add rule inet custos roles iifname %s oifname %s accept comment %s\n", wg, q(c.Network.WAN), q("vpn: peers exit through wan"))
		case in.MullvadUp:
			fmt.Fprintf(&b, "add rule inet custos roles iifname %s oifname %s accept comment %s\n", wg, q("wg-mullvad"), q("vpn: peers exit through Mullvad"))
		}
		fmt.Fprintf(&b, "add rule inet custos roles iifname %s counter drop comment %s\n", wg, q("vpn: kill switch (no other exit)"))
	}

	b.WriteString("\nflush chain inet custos policy_input\n")
	// cgnat-check asks the ISP router over UPnP; its SSDP answer is unicast
	// to the multicast query's port, which conntrack does not link.
	fmt.Fprintf(&b, "add rule inet custos policy_input iifname %s udp sport 1900 udp dport >= 32768 accept comment %s\n",
		q(c.Network.WAN), q("UPnP answers (cgnat-check)"))
	if c.VPN.Enabled {
		fmt.Fprintf(&b, "add rule inet custos policy_input iifname %s udp dport %d accept comment %s\n", q(c.Network.WAN), c.VPN.Port, q("vpn: WireGuard"))
		fmt.Fprintf(&b, "add rule inet custos policy_input iifname %s tcp dport { 443, 8443 } accept comment %s\n", wg, q("vpn: Custos UI/API"))
		fmt.Fprintf(&b, "add rule inet custos policy_input iifname %s icmp type echo-request limit rate 10/second accept\n", wg)
	}

	b.WriteString("\nflush chain inet custos policy_snat\n")
	if c.VPN.Enabled && c.VPN.Exit == "mullvad" && in.MullvadUp {
		fmt.Fprintf(&b, "add rule inet custos policy_snat oifname %s masquerade comment %s\n", q("wg-mullvad"), q("vpn: NAT behind the Mullvad address"))
	}
	return b.String()
}

// PeerIP returns the address of a peer (validated).
func PeerIP(p config.Peer) netip.Addr { a, _ := netip.ParseAddr(p.Address); return a }
